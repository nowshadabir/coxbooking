CREATE TABLE IF NOT EXISTS admins (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS hotels (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(190) NOT NULL,
  logo_path VARCHAR(500) DEFAULT NULL,
  location VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS room_categories (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(190) NOT NULL,
  slug VARCHAR(190) NOT NULL UNIQUE,
  description TEXT DEFAULT NULL,
  location VARCHAR(255) DEFAULT NULL,
  cover_path VARCHAR(500) DEFAULT NULL,
  price_from DECIMAL(12,2) NOT NULL DEFAULT 0,
  price_to DECIMAL(12,2) DEFAULT NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rooms (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  public_id CHAR(14) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  category_id BIGINT UNSIGNED NOT NULL,
  hotel_id BIGINT UNSIGNED DEFAULT NULL,
  name VARCHAR(190) NOT NULL,
  location VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  price_from DECIMAL(12,2) NOT NULL,
  guest_capacity VARCHAR(100) DEFAULT NULL,
  room_size VARCHAR(100) DEFAULT NULL,
  amenities TEXT DEFAULT NULL,
  cover_path VARCHAR(500) DEFAULT NULL,
  is_available TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_rooms_category FOREIGN KEY (category_id) REFERENCES room_categories(id) ON DELETE CASCADE,
  CONSTRAINT fk_rooms_hotel FOREIGN KEY (hotel_id) REFERENCES hotels(id) ON DELETE SET NULL,
  INDEX idx_rooms_category (category_id),
  INDEX idx_rooms_hotel (hotel_id),
  UNIQUE KEY uq_rooms_public_id (public_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS room_images (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  room_id BIGINT UNSIGNED NOT NULL,
  image_path VARCHAR(500) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_room_images_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
  INDEX idx_room_images_room (room_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS requests (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  request_type ENUM('booking','partner') NOT NULL DEFAULT 'booking',
  room_id BIGINT UNSIGNED DEFAULT NULL,
  room_name VARCHAR(190) DEFAULT NULL,
  guest_name VARCHAR(190) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(60) DEFAULT NULL,
  preferred_reply VARCHAR(60) DEFAULT NULL,
  checkin_date VARCHAR(40) DEFAULT NULL,
  checkout_date VARCHAR(40) DEFAULT NULL,
  guests VARCHAR(100) DEFAULT NULL,
  budget VARCHAR(100) DEFAULT NULL,
  notes TEXT DEFAULT NULL,
  property_name VARCHAR(190) DEFAULT NULL,
  property_role VARCHAR(190) DEFAULT NULL,
  property_location VARCHAR(255) DEFAULT NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'new',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_requests_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE SET NULL,
  INDEX idx_requests_type_status (request_type, status),
  INDEX idx_requests_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS saint_martin_requests (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(190) NOT NULL,
  whatsapp VARCHAR(60) NOT NULL,
  email VARCHAR(190) NOT NULL,
  members_count VARCHAR(100) NOT NULL,
  service_needed VARCHAR(100) NOT NULL,
  need_ship_ticket TINYINT(1) NOT NULL DEFAULT 0,
  need_hotel TINYINT(1) NOT NULL DEFAULT 0,
  approx_travel_date VARCHAR(60) NOT NULL,
  notes TEXT DEFAULT NULL,
  extra_requests TEXT DEFAULT NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'new',
  admin_notes TEXT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_sm_status (status),
  INDEX idx_sm_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

